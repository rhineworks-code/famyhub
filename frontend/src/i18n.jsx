const defaultCtx = {
    language: 'de',
    setLanguage: () => {},
    t: (key, params = {}) => {
        let text = de[key] || key;
        if (params) {
            Object.keys(params).forEach(p => {
                text = text.replaceAll(`{{${p}}}`, params[p]).replaceAll(`{{ ${p} }}`, params[p]);
            });
        }
        return text;
    },
};

const LanguageContext = React.createContext(defaultCtx);

export const LanguageProvider = ({ children, initialLanguage = 'de' }) => {
    const [language, setLanguage] = React.useState(initialLanguage);
    const t = (key, params = {}) => {
        let text = de[key] || key;
        if (params) {
            Object.keys(params).forEach(p => {
                text = text.replaceAll(`{{${p}}}`, params[p]).replaceAll(`{{ ${p} }}`, params[p]);
            });
        }
        return text;
    };
    return (
        <LanguageContext.Provider value={{ language, setLanguage, t }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useTranslation = () => {
    const ctx = React.useContext(LanguageContext);
    // Return ctx even if no Provider is found above — createContext(defaultCtx) guarantees it.
    return ctx;
};
